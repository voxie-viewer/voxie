def escapeCppString(str):
    b = bytes(str, 'utf-8')
    s = '"'
    for c in b:
        if c >= 32 and c < 127 and c != '"':
            s += chr(c)
        else:
            s += '\\{0:03o}'.format(c)
    s += '"'
    return s


def escapeCppList(li):
    s = "{"
    for val in li:
        s += escapeCppString(val) + ", "
    s += "}"
    return s


